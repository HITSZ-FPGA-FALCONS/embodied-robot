// ============================================================================
//  encoder_counter —— 正交编码器计数器（4 倍频）
// ----------------------------------------------------------------------------
//  功能：把编码器的 A/B 两相方波，变成"走了多少格"的位置计数。
//
//      A ──┐  ┌──┐  ┌──┐  ┌──
//          └──┘  └──┘  └──┘
//      B ────┐  ┌──┐  ┌──┐  ┌
//            └──┘  └──┘  └──┘
//          ↑  ↑  ↑  ↑  ↑  ↑  ← 每个边沿都计一次 = "四倍频"
//
//  正转（A 领先 B 90°）pos 增加，反转 pos 减少。
//
//  ────────────────────────────────────────────────────────────────────────────
//  ⚠️ 先别读实现。这个模块有三个核心思想，自己想出来才算学会：
//
//    Q1. A/B 是**异步**信号（编码器在板子外面，线很长，会带毛刺）。
//        直接拿它进状态机会怎样？应该怎么处理？
//
//    Q2. 只看 A 变了一次，能知道是正转还是反转吗？
//        —— 不能。那需要同时看什么？
//
//    Q3. "四倍频"的"四"是从哪来的？一个完整的电气周期里，
//        A 和 B 一共有几次边沿？
//
//  三个都想清楚 → 继续读，对照自己的答案。
//  想不清楚 → 先别看代码，那说明还没到能写它的时候。
//  ────────────────────────────────────────────────────────────────────────────
//
//  编码规范：本文件遵循 .claude/skills/shared/CodingStyle.md
//    · 可综合代码为 Verilog-2005，不使用 SystemVerilog 构造
//    · 同步复位，极性由最后一个参数 RS_LV 决定（默认 0 = 低有效）
//    · 寄存器后缀 _ff；clk / rst_n 恒为前两个端口
//
//  ⚠️ 与 clk_div.v / pwm_gen.v 的差异：那两个是异步复位
//     (always @(posedge clk or negedge rst_n))，**不符合本项目规范**，
//     已在 fpga/README.md 登记为存量不合规。本模块按规范写，
//     新模块请以本文件为准，不要照抄那两个。
// ============================================================================

`timescale 1ns / 1ps

module encoder_counter #(
    parameter POS_W = 32,       //! 位置计数器位宽
    parameter VEL_W = 16,       //! 速度输出位宽
    parameter RS_LV = 0         //! reset active level (0 = active-low)
) (
    input  wire                    clk,     //! 系统时钟 50 MHz
    input  wire                    rst_n,   //! 复位（极性由 RS_LV 决定）
    input  wire                    enc_a,   //! 编码器 A 相（**异步输入**）
    input  wire                    enc_b,   //! 编码器 B 相（**异步输入**）
    input  wire                    clr,     //! 单周期脉冲：清零 pos
    input  wire                    tick,    //! 测速采样使能，单周期脉冲
    output reg  signed [POS_W-1:0] pos,     //! 累计位置（count，二补码）
    output reg  signed [VEL_W-1:0] vel      //! 一个采样周期内的位置增量
);

    // ── 常量 ────────────────────────────────────────────────────────────────
    // 显式写位宽的"1"，避免工具在 signed 运算里按 32 位对齐出意外
    localparam signed [POS_W-1:0] POS_ONE = {{(POS_W-1){1'b0}}, 1'b1};

    // ========================================================================
    //  第一级：把异步的 A/B 打两拍同步
    // ========================================================================
    //
    //  相机里的"双重曝光"打比方：异步信号就像在晃动的车里拍照片，
    //  拍一次可能是模糊的。连拍两张，取第二张——它已经稳定了。
    //
    //  这就是"两级同步器"（2FF synchronizer）：
    //      第一拍可能采到亚稳态（一种既不是 0 也不是 1 的中间态），
    //      但到第二拍，它已经稳定成 0 或 1 了。
    //
    //  ⚠️ 为什么**不能**省掉这两拍：
    //     编码器线是长线，从板子外面进来。不采样会直接进状态机，
    //     毛刺会被当成真实的边沿，结果是**莫名其妙的多计数**——
    //     而且时有时无，极难复现。
    //
    //  ⚠️ 复位时把同步器清成 0，会产生一个已知的小副作用：
    //     如果复位释放那一刻编码器实际停在 01 / 10 / 11 状态，
    //     会多算 ±1 格。**这是设计如此的取舍**，解决办法见
    //     fpga/doc/encoder_counter.md §10（用 clr 在启动后清零）。
    reg [1:0] enc_a_sync_ff;
    reg [1:0] enc_b_sync_ff;

    always @(posedge clk)
        if (rst_n == RS_LV) begin
            enc_a_sync_ff <= 2'b00;
            enc_b_sync_ff <= 2'b00;
        end
        else begin
            enc_a_sync_ff <= {enc_a_sync_ff[0], enc_a};
            enc_b_sync_ff <= {enc_b_sync_ff[0], enc_b};
        end

    // 取第二拍（[1]）作为"干净的"输入
    wire       enc_a_s = enc_a_sync_ff[1];
    wire       enc_b_s = enc_b_sync_ff[1];
    wire [1:0] enc_cur = {enc_a_s, enc_b_s};

    // ========================================================================
    //  第二级：四倍频译码
    // ========================================================================
    //
    //  Q2 的答案：只看 A 变了不能判断方向，**必须看 A 和 B 的"上一次"和"这一次"**。
    //
    //  把 (上次A,上次B,这次A,这次B) 拼成一个 4 位码，就能唯一确定方向：
    //
    //      正转（A 领先 B）：10 → 11 → 01 → 00 → 10 ...
    //      反转：            10 → 00 → 01 → 11 → 10 ...
    //
    //  Q3 的答案：一个完整电气周期里 A 有 2 个边沿、B 有 2 个边沿，共 **4** 个。
    //             每个边沿计一次 → 四倍频 → 分辨率是编码器线数的 4 倍。
    //
    //  ⚠️ 那两个"看起来乱"的码（比如 0011、0110）是**非法跳变**——
    //     A 和 B 不可能在同一瞬间都变。默认分支把它们当 0 处理，
    //     这正是抗抖动的地方：毛刺产生的非法跳变不会计数。
    //
    //  ⚠️ 注意这里读的 `enc_prev_ff` 和 `enc_cur` 都是**本拍更新前**的值，
    //     所以译码比实际边沿晚一拍。**不影响累计结果**（每个边沿仍只计一次），
    //     但要心里有数：pos 不是"立刻"变的。
    reg  [1:0] enc_prev_ff;
    wire [3:0] enc_trans = {enc_prev_ff, enc_cur};

    always @(posedge clk)
        if (rst_n == RS_LV) begin
            enc_prev_ff <= 2'b00;
            pos         <= {POS_W{1'b0}};
        end
        else begin
            enc_prev_ff <= enc_cur;

            if (clr) begin
                pos <= {POS_W{1'b0}};
            end
            else begin
                case (enc_trans)
                    // 正转（A 领先 B）
                    4'b1011, 4'b1101, 4'b0100, 4'b0010: pos <= pos + POS_ONE;
                    // 反转
                    4'b0001, 4'b0111, 4'b1110, 4'b1000: pos <= pos - POS_ONE;
                    // 没变，或非法跳变（含毛刺）
                    default:                            pos <= pos;
                endcase
            end
        end

    // ========================================================================
    //  第三级：测速
    // ========================================================================
    //
    //  速度 = 一段时间里走了多少格。所以需要两样东西：
    //      ① 一个"上次采样时的位置"  → vel_base_ff
    //      ② 一个"什么时候该采样"的信号 → tick
    //
    //  ⚠️ 时间基准**不由本模块产生**。`tick` 由外部给出
    //     （通常来自 clk_div，比如 20 ms 一次），这样全设计只有一个时钟域。
    //
    //  ⚠️ vel 是**增量（count/采样周期）不是物理速度**。换算成 mm/s
    //     需要轮径和编码器线数，那是上层 odom 模块的事——本模块不掺和，
    //     免得两个地方各换算一次、还各算错一次。
    reg  signed [POS_W-1:0] vel_base_ff;
    wire signed [POS_W-1:0] vel_delta = pos - vel_base_ff;

    always @(posedge clk)
        if (rst_n == RS_LV) begin
            vel         <= {VEL_W{1'b0}};
            vel_base_ff <= {POS_W{1'b0}};
        end
        else if (clr) begin
            // ⚠️ clr 把 pos 清零，速度基准**必须跟着归零**。
            //    否则下一个 tick 会算出 (0 - 旧位置)，是个巨大的负值——
            //    看起来像"车倒着飞出去了"，而且只在 clr 之后出现一次，
            //    极难定位。
            //    代价：clr 与 tick 同一拍时，这次采样被跳过（clr 优先）。
            vel_base_ff <= {POS_W{1'b0}};
        end
        else if (tick) begin
            // 只取低 VEL_W 位。采样周期内不可能走满 16 位
            // （20 ms @ 500 线 × 4 倍频 × 5 转/s ≈ 200），截断是安全的。
            vel         <= vel_delta[VEL_W-1:0];
            vel_base_ff <= pos;
        end

endmodule
