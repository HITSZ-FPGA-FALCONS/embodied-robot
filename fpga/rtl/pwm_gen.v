// ============================================================================
//  pwm_gen —— PWM 生成器（电机调速用）
// ----------------------------------------------------------------------------
//  功能：把一个"占空比数值"变成一根引脚上的方波。
//
//       duty = 0          → 恒低      0%
//       duty = PERIOD/2   → 方波      50%
//       duty = PERIOD     → 恒高      100%
//
//  ────────────────────────────────────────────────────────────────────────────
//  ⚠️ 先别读下面的实现。这个模块只有一个核心思想，自己想出来才算学会。
//
//  在往下看之前，先回答三个问题（写在纸上或心里默答）：
//
//    Q1. PWM 的本质是"一个周期里有百分之几的时间是高电平"。
//        如果你想在 FPGA 里实现"百分之几"，你需要一个什么东西在数时间？
//
//    Q2. 假设时钟 50 MHz，想要 20 kHz 的 PWM，那一个 PWM 周期里
//        有多少个时钟周期？（这叫 PERIOD，先自己算出来）
//
//    Q3. 有了 PERIOD，如果 duty = 1250，输出应该在什么时候高、什么时候低？
//
//  三个问题都能答上来 → 继续读，对照自己的思路。
//  答不上来 → 回去把 `clk_div.v` 的计数器部分再过一遍，这里不重复讲计数器。
//  ────────────────────────────────────────────────────────────────────────────
//
//  接口（冻结于 docs/architecture/Interface_v0.1_接口表.md §3.1）
//  ────────────────────────────────────────────────────────────────────────────
//    clk    输入  系统时钟 50 MHz
//    rst_n  输入  复位，低有效
//    en     输入  0 = 强制输出低（电机停），并让计数器归零
//    duty   输入  占空比计数值，取值 0 ~ PERIOD
//    dir    输入  方向，直通到 dir_o（本模块不处理方向）
//    pwm    输出  PWM 波形
//    dir_o  输出  方向输出
//
//  参数
//    CLK_HZ   输入时钟频率，默认 50_000_000
//    PWM_HZ   PWM 频率，默认 20_000，必须整除 CLK_HZ
//    DUTY_W   duty 位宽，必须满足 2^DUTY_W > PERIOD
//
//  ────────────────────────────────────────────────────────────────────────────
//  为什么输出"打一拍"再送出去？
//  ────────────────────────────────────────────────────────────────────────────
//  如果写成组合逻辑：
//        assign pwm = (cnt < duty);
//  那么 duty 每变一次，pwm 就可能立刻出现一个窄毛刺。
//  电机驱动器的输入是真实引脚，毛刺会被 H 桥当成一次真实的开关动作。
//
//  打成寄存器后，pwm 只在时钟沿变化，毛刺被时钟"过滤"掉了。
//  代价是输出比内部比较结果晚一个时钟周期——本模块的占空比不受影响。
//
//  ⚠️ 代价细节：因为打了一拍，高电平的**位置**整体后移 1 个周期，
//     但一个周期内高电平的**拍数**不变，所以占空比仍然精确。
// ============================================================================

`timescale 1ns / 1ps

module pwm_gen #(
    parameter CLK_HZ = 50_000_000,      // 输入时钟频率
    parameter PWM_HZ = 20_000,          // PWM 频率，必须整除 CLK_HZ
    parameter DUTY_W = 12               // duty 位宽
)(
    input  wire              clk,
    input  wire              rst_n,
    input  wire              en,
    input  wire [DUTY_W-1:0] duty,
    input  wire              dir,
    output reg               pwm,
    output wire              dir_o
);

    // ── 一个 PWM 周期有多少个时钟 ────────────────────────────────────────────
    // 50_000_000 / 20_000 = 2500
    //
    // ⚠️ 这里用的是整数除法。如果 CLK_HZ 不能被 PWM_HZ 整除，
    //    实际频率会和你想的不一样（而且不报错）。
    //    在 testbench 里用 $display 把 PERIOD 打出来确认，是个好习惯。
    localparam PERIOD = CLK_HZ / PWM_HZ;

    // ── 计数器位宽 ──────────────────────────────────────────────────────────
    // 和 clk_div.v 里是同一件事：要装得下 PERIOD-1。
    // $clog2(2500) = 12，12 位最大 4095 ≥ 2499 ✓
    //
    // ⚠️ duty 需要装得下 PERIOD 本身（因为有 100% 这一档），
    //    而 PERIOD 比 cnt 的最大值大 1，所以 DUTY_W 必须满足 2^DUTY_W > PERIOD。
    //    PERIOD=2500 → DUTY_W 至少 12（2^12 = 4096 > 2500）✓
    localparam CNT_W = $clog2(PERIOD);

    reg [CNT_W-1:0] cnt;

    assign dir_o = dir;                 // 方向不进状态机，直接透传

    // ── 主逻辑 ──────────────────────────────────────────────────────────────
    //
    //  核心只有一行：      pwm <= (cnt < duty);
    //
    //  为什么这一行就对了？数一数：
    //     cnt 在 0, 1, 2, ... , PERIOD-1 之间循环
    //     当 cnt < duty 时为高 → 一个周期里正好有 duty 拍是高
    //     一个周期总共有 PERIOD 拍
    //     → 占空比 = duty / PERIOD   ✓
    //
    //  两个边界情况：
    //     duty = 0      →  cnt < 0 永远为假 → 恒低 ✓
    //     duty = PERIOD →  cnt < PERIOD 永远为真（cnt 最大只到 PERIOD-1）→ 恒高 ✓
    //
    //  所以**不需要**为 0% 和 100% 写任何特殊分支。
    //  如果发现自己写了 "if (duty == 0) ... else if (duty == PERIOD) ..."，
    //  说明还没想清楚——回头再看一遍上面这五行。
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            cnt <= {CNT_W{1'b0}};
            pwm <= 1'b0;
        end
        else if (!en) begin
            // 停的时候把计数器也归零。
            // 否则重新使能时可能从半周期开始，第一个 PWM 周期是残的——
            // 对电机来说就是一次莫名其妙的窄脉冲。
            cnt <= {CNT_W{1'b0}};
            pwm <= 1'b0;
        end
        else begin
            // 计数器：数满一个周期就回零
            if (cnt == PERIOD - 1) cnt <= {CNT_W{1'b0}};
            else                   cnt <= cnt + 1'b1;

            // 输出：只在这一个地方算，避免两处写法不一致
            pwm <= (cnt < duty);
        end
    end

endmodule
