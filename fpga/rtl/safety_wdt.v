// ============================================================================
//  safety_wdt —— 安全看门狗
// ----------------------------------------------------------------------------
//  功能：盯着"上层还活着吗"。上层每次活干完要踢一脚（kick 脉冲）；
//        超过 timeout_ms 没踢，就拉高 fault、并切断 PWM 使能。
//
//  ────────────────────────────────────────────────────────────────────────────
//  为什么这个模块是"必须有"的
//  ────────────────────────────────────────────────────────────────────────────
//  赛题里有一条得分点：**AI 异常时，底层安全控制仍要保持有效。**
//
//      边缘 AI（树莓派 / Jetson）可能崩溃、卡死、被拔线，或者只是跑得慢。
//      如果 AI 直接控制 PWM，它一挂车就失控。
//
//      所以架构底线是：**AI 只能给"速度指令"，不能直接碰 PWM。**
//      中间隔着一层 FPGA 侧的安全逻辑——就是这个模块。
//      心跳断了 → 200 ms 内停车。
//
//  ────────────────────────────────────────────────────────────────────────────
//  ⚠️ 先别读实现。这个模块只有一个核心思想，自己想出来才算学会：
//
//    Q1. "超过 200 ms 没有踢" —— 要判断"多久"，你需要什么？（提示：不是时钟本身）
//
//    Q2. 计数器数到阈值之后，该继续数吗？继续数会有什么问题？
//
//    Q3. 故障已经发生、上层又开始正常踢狗了，应该自动恢复吗？
//        如果自动恢复，"故障一直存在"会变成什么现象？
//
//  ────────────────────────────────────────────────────────────────────────────
//  编码规范：遵循 .claude/skills/shared/CodingStyle.md（同步复位 + RS_LV）
// ============================================================================

`timescale 1ns / 1ps

module safety_wdt #(
    parameter CLK_HZ = 50_000_000,  //! 系统时钟频率（用于把 ms 换算成周期数）
    parameter RS_LV  = 0            //! reset active level (0 = active-low)
) (
    input  wire        clk,         //! 系统时钟
    input  wire        rst_n,       //! 复位（极性由 RS_LV 决定）
    input  wire        kick,        //! 单周期脉冲：喂狗。必须**周期性**给
    input  wire [15:0] timeout_ms,  //! 超时阈值（毫秒）
    output reg         fault,       //! 高 = 已超时（**锁存，只能靠复位清除**）
    output wire        pwm_en       //! 直接串到 pwm_gen 的 en 上
);

    // ── ms 换算成时钟周期 ───────────────────────────────────────────────────
    // 50 MHz → 每毫秒 50_000 个周期。
    // ⚠️ 这里用的是整数除法。CLK_HZ 必须能被 1000 整除，否则换算有误差。
    localparam CYC_PER_MS = CLK_HZ / 1000;

    // 阈值最大 65535 ms × 50000 = 3.28e9，仍在 32 位内（4.29e9），不会溢出
    wire [31:0] timeout_cyc = timeout_ms * CYC_PER_MS;

    // ── 超时计数 ────────────────────────────────────────────────────────────
    //
    //  Q1 的答案：需要**计数**。时钟只告诉你"过了一拍"，
    //             数够 CYC_PER_MS 拍才知道过了 1 ms。
    //
    //  Q2 的答案：数到阈值就**不该再数了**。继续数会回绕（wrap），
    //             回绕之后再比较大小就会出错——故障时有时无。
    //             所以下面的实现数到阈值就停住，并且**立即置 fault**。
    //
    //  Q3 的答案：**绝对不能自动恢复。**
    //             如果故障后上层又开始踢狗、看门狗就自动恢复，那么
    //             "故障持续存在"会变成"周期性抽搐"——车每 200 ms 动一下，
    //             比干脆停住更危险（既有动力、又不可控）。
    //             所以 fault 一旦置位就锁存，只有 rst_n 能清。
    reg [31:0] cnt_ff;

    always @(posedge clk)
        if (rst_n == RS_LV) begin
            cnt_ff <= 32'd0;
            fault  <= 1'b0;
        end
        else if (fault) begin
            // 已故障：保持。这里**故意不看 kick** ——
            // 即使上层重新开始踢狗也不恢复。
            cnt_ff <= cnt_ff;
        end
        else if (kick) begin
            // 喂狗：计数器从头开始
            cnt_ff <= 32'd0;
        end
        else if (cnt_ff >= timeout_cyc) begin
            // 数满还没被喂 → 故障。计数器停在原地（不再自增，避免回绕）
            cnt_ff <= cnt_ff;
            fault  <= 1'b1;
        end
        else begin
            cnt_ff <= cnt_ff + 32'd1;
        end

    // ── 输出 ────────────────────────────────────────────────────────────────
    // fault 是寄存器，所以这里不需要再打一拍，也不会产生毛刺。
    assign pwm_en = ~fault;

    // ⚠️ timeout_ms = 0 时，timeout_cyc = 0，看门狗会在**下一拍立刻触发**。
    //    这是**故意的（fail-safe）**：阈值配错时宁可立即停车，也不能永不触发。
    //    一个"配错了就静默失效"的看门狗，等于没有看门狗。

endmodule
