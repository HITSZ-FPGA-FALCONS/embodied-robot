// ============================================================================
//  clk_div —— 分频器（输出单周期使能脉冲）
// ----------------------------------------------------------------------------
//  功能：每 DIV 个时钟周期，输出一个宽度为 1 个时钟周期的 tick 脉冲
//
//  为什么输出"脉冲"而不是"分频后的时钟"？
//  ────────────────────────────────────────
//  这是本模块最重要的设计决策，请务必理解：
//
//  ❌ 不推荐：用计数器翻转产生一个新的慢时钟
//        always @(posedge clk) if (cnt==N) slow_clk <= ~slow_clk;
//        然后把 slow_clk 接到别的模块当时钟用
//
//     问题：这样会造出**第二个时钟域**。两个时钟域之间的信号必须做
//           跨时钟域同步（打两拍），否则会出现亚稳态——一种时有时无、
//           极难复现的随机故障。
//
//  ✅ 推荐：所有逻辑都跑在同一个时钟上，只产生"什么时候该干活"的脉冲
//        if (tick) begin ... end
//
//     好处：整个设计只有一个时钟域，不需要任何同步器。
//
//  所以本模块输出 tick，而不是输出一个分频时钟。
//  需要"慢动作"时，用 `if (tick)` 作为条件即可。
//
//  ────────────────────────────────────────────────────────────────────────────
//  接口
//  ────────────────────────────────────────────────────────────────────────────
//    clk    输入  系统时钟（板上为 50 MHz，引脚 Y18）
//    rst_n  输入  复位，低有效
//    tick   输出  每 DIV 个周期出一次的高电平脉冲，宽度 1 个周期
//
//  参数
//    DIV    分频比，默认 50_000_000 → 50MHz 下每秒一个 tick
//
//  ────────────────────────────────────────────────────────────────────────────
//  用法示例：1Hz 闪烁
//  ────────────────────────────────────────────────────────────────────────────
//    clk_div #(.DIV(50_000_000)) u_div (
//        .clk(clk), .rst_n(rst_n), .tick(tick_1hz)
//    );
//    always @(posedge clk or negedge rst_n)
//        if (!rst_n) led <= 1'b0;
//        else if (tick_1hz) led <= ~led;      // 每秒翻转一次
// ============================================================================

`timescale 1ns / 1ps

module clk_div #(
    parameter DIV = 50_000_000          // 分频比，必须 ≥ 2
)(
    input  wire clk,
    input  wire rst_n,
    output reg  tick
);

    // ── 计数器位宽 ──────────────────────────────────────────────────────────
    // 需要能装下 DIV-1，否则计数器会提前回绕、分频比就错了。
    //
    // $clog2(N) 返回"装下 N 需要多少位"，例如：
    //     $clog2(2)  = 1        2 需要 1 位
    //     $clog2(8)  = 3
    //     $clog2(9)  = 4        9 需要 4 位（3 位最大只到 7）
    //
    // 位宽算错是新手最常见的分频器 bug：DIV 稍大一点就出错，
    // 而且现象是"频率不对"而不是"不工作"，很难查。
    localparam CNT_W = $clog2(DIV);

    reg [CNT_W-1:0] cnt;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            cnt  <= {CNT_W{1'b0}};
            tick <= 1'b0;
        end
        else if (cnt == DIV - 1) begin
            cnt  <= {CNT_W{1'b0}};
            tick <= 1'b1;               // 只在归零这一拍拉高
        end
        else begin
            cnt  <= cnt + 1'b1;
            tick <= 1'b0;               // 其余时间保持低
        end
    end

endmodule
