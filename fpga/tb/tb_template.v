module tb_template;

    // ────────────────────────────────────────────────────────────────────────
    //  1. 信号定义
    //     给 DUT 输入的信号 → 用 reg（因为在 initial 里赋值）
    //     从 DUT 输出的信号 → 用 wire（因为由 DUT 驱动）
    //
    //     这个 reg/wire 的区分是新手最容易搞混的地方：
    //     reg  = 我（testbench）要主动给它赋值
    //     wire = 我只看，DUT 负责驱动
    // ────────────────────────────────────────────────────────────────────────

    reg  clk;
    reg  rst_n;
    // [TODO] reg  [宽度] 你的输入信号;
