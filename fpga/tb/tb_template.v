    // ────────────────────────────────────────────────────────────────────────
    //  2. 例化被测模块（DUT = Device Under Test）
    //     语法：模块名 实例名 ( .模块端口(你的信号), ... );
    //     端口名前那个点"."不能省，它是"按名字连接"
    // ────────────────────────────────────────────────────────────────────────

    counter #(                  // [TODO] 改成你的模块名
        .WIDTH(8)               // [TODO] 参数（如果模块有 parameter 的话）
    ) u_dut (
        .clk   (clk),
        .rst_n (rst_n),
        .count (count)          // [TODO] 补齐你的端口
    );

    // ────────────────────────────────────────────────────────────────────────
    //  3. 时钟生成
    //     板上是 50MHz → 周期 20ns → 每 10ns 翻转一次
    //     仿真时可以先用更快的时钟（比如 10ns 周期）省时间，
    //     但**验证时序相关的逻辑（如串口波特率）必须用真实频率**
    // ────────────────────────────────────────────────────────────────────────

    localparam CLK_PERIOD = 20;     // [TODO] 单位 ns

    initial clk = 1'b0;
    always #(CLK_PERIOD/2) clk = ~clk;

    // ────────────────────────────────────────────────────────────────────────
    //  4. 激励与检查
    //     initial 块在 0 时刻开始，顺序执行
    // ────────────────────────────────────────────────────────────────────────

    initial begin
        // 4.1 波形输出（用 ModelSim 时这行让波形自动记录）
        $dumpfile("tb_template.vcd");
        $dumpvars(0, tb_template);

        // 4.2 初始化
        rst_n = 1'b0;               // 先按住复位
