// ============================================================================
//  新手常踩的坑
// ----------------------------------------------------------------------------
//  1. reg/wire 搞反 —— DUT 输出必须用 wire 接，写成 reg 会得到 x（不定态）
//  2. 忘了释放复位 —— rst_n 一直是 0，输出永远不动
//  3. 复位只维持了 0ns —— 没跨过时钟沿，时序逻辑根本没看到复位
//  4. #10 在 always 块里写 —— 时钟生成用 always #(周期/2)，别和 @(posedge) 混
//  5. 只看波形不写检查 —— 回归测试时你会需要自动判断通过/失败
